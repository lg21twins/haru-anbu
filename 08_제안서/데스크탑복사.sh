#!/bin/bash
# 제안서 일체를 데스크탑에 자체 완결 폴더로 복사한다.
#
#   bash 08_제안서/데스크탑복사.sh
#
# 왜 스크립트인가 — 손으로 복사하면 두 가지를 빼먹는다.
#   1) 시각화 HTML이 참조하는 07_디자인/tokens/tokens.css (없으면 HTML이 깨진다)
#   2) 참고리서치와 작업기록 (제안서의 근거가 여기 있다)
#
# 폴더명에 날짜가 붙으므로 기존 묶음을 덮어쓰지 않는다.

set -e
SRC="$(cd "$(dirname "$0")/.." && pwd)"
DATE="$(date +%Y%m%d)"
DST="$HOME/Desktop/하루안부_제안서_$DATE"

# 뽑기 전에 표현·수치 위반부터 잡는다. 틀린 PDF를 배포하지 않기 위해서다.
if ! python3 "$SRC/08_제안서/점검.py"; then
  echo
  echo "점검기가 위반을 잡았다. 고치고 PDF를 다시 뽑은 뒤에 복사한다."
  # 다만 **결정지 한 장은 내보낸다.**
  # 지금 걸리는 위반 중에는 "사람이 정해야 풀리는" 것이 있는데(의료진 화면),
  # 결정지까지 같이 막으면 **푸는 방법을 손에 못 쥔 채로 막히는** 셈이다.
  DEC="$SRC/08_제안서/PDF/하루안부_의료진화면_결정지.pdf"
  if [ -f "$DEC" ]; then
    cp "$DEC" "$HOME/Desktop/★먼저_정할것_의료진화면.pdf"
    echo "→ 결정지는 바탕화면에 뒀다: ★먼저_정할것_의료진화면.pdf (2쪽, 보면 끝난다)"
  fi
  exit 1
fi

# 우리 숫자도 다시 센다. 남의 수치만 검증하면 안 된다. (실패해도 멈추지는 않는다)
python3 "$SRC/08_제안서/숫자검사.py" | tail -2

# 쪽 모양도 본다. 글자가 맞아도 빈 쪽이 섞여 나갈 수 있다. (실패해도 멈추지는 않는다)
python3 "$SRC/08_제안서/쪽검사.py" | tail -3

# 배포에 빠질 에셋도 본다. 제안서가 가장 많이 하는 말이 "공개 배포 중입니다"인데
# 미추적 파일이 섞여 있으면 그 문장부터 무너진다. (실패해도 멈추지는 않는다)
python3 "$SRC/07_디자인/scripts/untracked_deps.py" | head -3

rm -rf "$DST"
# 상황별로 폴더를 나눈다. 파일이 많은 게 문제가 아니라 "지금 뭘 집어야 하나"가 문제였다.
# 1·2·3 안에 있는 것만 실제로 밖으로 나간다. 나머지는 전부 _전체자료/ 아래로 내린다.
# 종합보고 쪽수는 PDF에서 계산한다. 안내문에 하드코딩해 뒀더니 61쪽에 멈춰 있었다.
NP=$(python3 -c "import re;print(len(re.findall(rb'/Type\\s*/Page[^s]',open('$SRC/08_제안서/PDF/하루안부_종합보고.pdf','rb').read())))")

mkdir -p "$DST/1_교수님께_보낼것" "$DST/2_코엑스에_들고갈것" "$DST/3_명함받고_보낼것" \
         "$DST/4_KB에_보낼것" \
         "$DST/_전체자료/08_제안서" "$DST/_전체자료/07_디자인/tokens" "$DST/_전체자료/참고리서치"

# 1) 제안서 본체 — _원본백업(20MB 구버전 보관본)은 읽을 값이 없어 뺀다
cd "$SRC/08_제안서"
cp -R PDF 원고 시각화 assets README.md 점검.py "$DST/_전체자료/08_제안서/"
[ -f 먼저_읽기.html ] && cp 먼저_읽기.html "$DST/"

# 1-A) 지금 사람이 정해야 하는 것 — 폴더 맨 위에 둔다.
# 하위 폴더에 넣으면 "나중에 볼 것"이 되고, 그러면 8/14 인쇄가 그냥 지나간다.
[ -f PDF/하루안부_의료진화면_결정지.pdf ] && \
  cp PDF/하루안부_의료진화면_결정지.pdf "$DST/★먼저_정할것_의료진화면.pdf"

# 1-B) 상황별 — 헷갈릴 여지를 없앤다
cp PDF/하루안부_종합보고.pdf                                   "$DST/1_교수님께_보낼것/"
cp PDF/하루안부_KHF팀브리핑.pdf PDF/하루안부_KHF인쇄물.pdf \
   PDF/하루안부_KHF현장실행팩.pdf PDF/하루안부_의향확인서.pdf \
   PDF/하루안부_데이터파기확인서.pdf                            "$DST/2_코엑스에_들고갈것/"
cp PDF/하루안부_짧은제안서.pdf                                  "$DST/3_명함받고_보낼것/"
# 회신이 오면 보낼 것. 먼저 첨부하지는 않는다.
cp PDF/하루안부_짧은제안서.pdf                                  "$DST/4_KB에_보낼것/"

# 폴더마다 "이걸 왜 여기 뒀는지" 한 장씩. 나중에 열었을 때 설명이 없으면 다시 헤맨다.
cat > "$DST/2_코엑스에_들고갈것/읽어보기.txt" <<TXT
코엑스 KHF 2026 (8/19~21) 현장용
============================================================

인쇄해서 들고 가는 것
  하루안부_KHF인쇄물.pdf      4쪽
      앞 2쪽 = 상대에게 주는 A4 한 장의 앞뒤 → 양면 20부
      뒤 2쪽 = 우리가 쓰는 것 → 현장카드 3부 · 인터뷰 메모지 30부
  하루안부_의향확인서.pdf     1쪽  현장에서 받는 서식. 넉넉히
  하루안부_데이터파기확인서.pdf 1쪽 "정보 어떻게 되냐"는 질문의 답. 몇 부만

가기 전에 읽는 것
  하루안부_KHF팀브리핑.pdf    2쪽  3인이 이것만 외우면 된다
  하루안부_KHF현장실행팩.pdf 15쪽  사흘 라우트 · 스크립트 · 반론 대응

부스에서 종이로 주는 것은 A4 한 장이 전부다.
${NP}쪽 종합보고는 들고 가지 않는다 — 대신
"한계랑 법 검토까지 ${NP}쪽으로 정리한 게 있는데 보내드릴까요"가
명함을 받는 자연스러운 이유가 된다.

진짜 무기는 종이가 아니라 폰이다. haruanbu.site 가 그 자리에서 열린다.
출발 전에 폰에서 직접 한 번 열어볼 것.
TXT

cat > "$DST/3_명함받고_보낼것/읽어보기.txt" <<TXT
명함을 주고받은 뒤 — 그날 저녁 ~ 사흘 안에
============================================================

  하루안부_짧은제안서.pdf   8쪽

부스에서 A4 한 장은 이미 드렸고, ${NP}쪽은 아직 부담스러운 구간이 있다.
그 사이를 메우는 유일한 문서다.

받는 사람이 교수님이 아니라 시설·요양사업자라
"산학협력단 경유"·"캡스톤" 같은 학교 내부 사정은 빼고 썼다.

메일에 붙일 때
  · 첨부는 이거 하나만. 여러 개면 어느 걸 먼저 열지부터 정해야 한다
  · 당일 저녁에 3줄로 먼저 보내고, D+3에 이걸 붙이는 순서가 낫다
  · 메일 문안은 _전체자료/08_제안서/원고/13_KHF_현장실행팩.md 의 후속 메일 절에
  · 영문이면 원고 20번

${NP}쪽 종합보고는 "달라고 하실 때만" 보낸다. 먼저 보내지 않는다.
TXT
# 4_KB — 조사한 제출처 중 공식 제안 창구가 공개된 유일한 곳이다. 문안을 뽑아 넣는다.
python3 - "$DST" <<'PYEOF'
import re, sys, os
dst = sys.argv[1]
s = open("원고/07_1페이지_소개서.md", encoding="utf-8").read()
sec = s[s.index("## F. KB골든라이프케어 발송본"):]
mail = re.search(r"```\n(제목:.*?)\n```", sec, re.S).group(1)
out = f"""KB골든라이프케어 — 지금 보낼 수 있다
{"=" * 60}

받는 곳   kbglc00610@kbgoldenlifecare.co.kr   (마케팅 제휴·비즈니스 제안)
보조      본사 02-2135-8914

조사한 제출처 가운데 공식 제안 창구가 공개된 유일한 곳이다.
다른 곳은 대표번호로 전화해 부서를 찾아 들어가야 한다.

첨부는 붙이지 않는다. 본문만 보낸다.
회신이 오면 그때 이 폴더의 하루안부_짧은제안서.pdf 하나만 보낸다.

보내기 전에 확인
  · team@haruanbu.site 메일함이 실제로 열려 있는가  ← 이게 안 되면 보내지 않는다
  · haruanbu.site 가 폰에서 열리는가
  · 상대 회사 숫자를 우리가 틀리지 않았는가 (시설 10곳은 공식 사이트 확인값,
    매출 208억은 확인 실패한 수치라 본문에 없다)

무응답이면 2주 뒤 한 번만. 두 번은 보내지 않는다.

{"=" * 60}

{mail}
"""
open(os.path.join(dst, "4_KB에_보낼것", "메일_본문.txt"), "w", encoding="utf-8").write(out)
PYEOF

python3 - "$DST" <<'PYEOF'
import re, sys, os
dst = sys.argv[1]
src = os.path.join(os.path.dirname(os.path.abspath(__file__)) if "__file__" in dir() else ".", "")
p = "원고/15_교수님_보고_및_요청.md"
s = open(p, encoding="utf-8").read()
body = re.search(r"## 2\. 메일 본문 초안\s*\n```\n(.*?)\n```", s, re.S).group(1)
out = ("메일 본문 초안 — 그대로 붙여넣으시면 됩니다.\n"
       "보내기 전에 이름·연락처만 확인하세요.\n"
       "첨부는 이 폴더의 하루안부_종합보고.pdf 하나입니다.\n" + "=" * 60 + "\n\n" + body + "\n")
open(os.path.join(dst, "1_교수님께_보낼것", "메일_본문.txt"), "w", encoding="utf-8").write(out)

# 카톡·문자 4종도 같이 뽑는다 (§2-B의 코드블록)
kk = s[s.index("## 2-B."):s.index("## 3. 대면으로")]
blocks = re.findall(r"### ([^\n]+)\n\n```\n(.*?)\n```", kk, re.S)
lines = ["카톡 · 문자 초안 — 상황에 맞는 것 하나만 골라 그대로 붙여넣으세요.",
         "메일을 먼저 보내고, 카톡은 그 뒤에 보냅니다. 이모지는 쓰지 않습니다.", "=" * 60, ""]
for title, b in blocks:
    lines += ["", "[" + title.strip() + "]", "-" * 60, b, ""]
lines += ["=" * 60,
          "카톡에 쓰지 않는 것: 수치 나열(자랑으로 읽힌다) · 미구현 기능 · 파일 첨부(메일로) · 밤 10시 이후 발송 · 답장 재촉",
          "보내기 전: 메일을 먼저 보냈는가 / haruanbu.site 폰에서 열리는지 / 이름을 맨 앞에 밝혔는가 / 요청이 둘을 넘지 않는가"]
open(os.path.join(dst, "1_교수님께_보낼것", "카톡_문자.txt"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
PYEOF

# 2) 시각화 HTML의 ../../07_디자인/tokens/tokens.css 가 풀리도록
cp "$SRC/07_디자인/tokens/tokens.css" "$DST/_전체자료/07_디자인/tokens/"

# 3) 참고 리서치 — 제안서 수치·주장의 원자료
cd "$SRC"
for f in \
  "중간고사기획서/_제안서_리서치_20260723.md" \
  "01_기획/하루안부_통합기획서_v6.0.md" \
  "01_기획/하루안부_서비스개선안_v1.0.md" \
  "04_리서치/하루안부_분석보고서.md" \
  "04_리서치/의료인_인터뷰_질문지.txt" \
  "04_리서치/케어플랫폼_인터뷰가이드_v1.0.txt" \
  "02_시장조사/케어플랫폼_레퍼런스앱_조사보고서.md" \
  "02_시장조사/케어플랫폼_경쟁사_시장조사_v3.0.txt" \
  "02_시장조사/하루안부_포지셔닝맵_v2.0.txt" \
  "02_시장조사/하루안부_전략분석_v1.0.txt" ; do
  [ -f "$f" ] && cp "$f" "$DST/_전체자료/참고리서치/" || echo "  (없음, 건너뜀) $f"
done

# 4) 작업기록 — 제안서 구간만. 무엇을 왜 그렇게 정했는지의 근거
LOG="06_로그/대화기록_작업로그.md"
START=$(grep -n "^## 2026.08.02 제안서 작업" "$LOG" | head -1 | cut -d: -f1)
{
  echo "# 하루안부 제안서 — 작업 기록"
  echo
  echo "> \`$LOG\`에서 제안서 관련 구간만 뽑았다."
  echo "> 무엇을 왜 그렇게 정했는지의 기록이다. 결정의 근거가 필요할 때 여기를 본다."
  echo
  echo "---"
  echo
  tail -n "+$START" "$LOG"
} > "$DST/_전체자료/작업기록_제안서.md"

echo
echo "복사 완료 — $DST"
echo "  $(find "$DST" -type f | wc -l | tr -d ' ')개 파일 · $(du -sh "$DST" | cut -f1)"
echo "  1_교수님께 / 2_코엑스 / 3_명함받고 / 4_KB에 — 이 넷만 밖으로 나간다."
echo "  나머지는 전부 _전체자료/ 안에 있다. 먼저_읽기.html 을 더블클릭하면 전체가 보인다."
